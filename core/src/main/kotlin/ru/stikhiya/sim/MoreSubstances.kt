        Substance(key, name, P.SOLID, C.METAL, color, density = density, heatCapacity = cp, conductivity = k,
            colorVar = 0.03f, hotAt = melt, hotTo = "molten_$key", hotLatent = latent, description = desc),
        Substance("molten_$key", molten, P.LIQUID, C.METAL, glow(color), density = liqDensity, heatCapacity = liqCp,
