package ru.stikhiya.sim

import ru.stikhiya.sim.Category as C
import ru.stikhiya.sim.Phase as P
import ru.stikhiya.sim.Tag as T

/**
 * Вещества 259–500. Свойства — справочные (плотность, теплоёмкость, теплопроводность, температуры и теплоты
 * переходов, горение, электропроводность). Поведение в реакциях задают теги [Tag] и правила в [Reactions].
 */
object NewSubstances {

    private fun metal(
        key: String, name: String, molten: String, color: Int, density: Float, cp: Float, k: Float,
        melt: Float, latent: Float, liqDensity: Float, tags: Int = T.METAL, flame: Int = 0, elec: Float = Float.NaN,
        burn: Float = 0f, flameT: Float = 1500f, oxy: Float = 0.5f, burnTo: String? = null, bounce: Float = Float.NaN,
        desc: String = ""
    ): List<Substance> = listOf(
        Substance(key, name, P.SOLID, C.METAL, color, density = density, heatCapacity = cp, conductivity = k,
            colorVar = 0.03f, hotAt = melt, hotTo = "molten_$key", hotLatent = latent, tags = tags, flame = flame,
            elec = elec, bounce = bounce,
            flashPoint = if (burn > 0f) melt * 0.8f + 100f else Float.NaN,
            autoIgnition = if (burn > 0f) melt * 0.8f + 200f else Float.NaN,
            burnTime = 15f, burnHeat = burn, burnTo = burnTo, burnResidue = if (burnTo != null) 1f else 0f,
            smoke = if (burn > 0f) 0.3f else 0f, flameTemp = flameT, oxygenNeed = oxy, description = desc),
        Substance("molten_$key", molten, P.LIQUID, C.METAL, glow(color), density = liqDensity, heatCapacity = cp * 1.15f,
            conductivity = k * 0.4f, spawnTemp = melt + 60f, spread = 4, viscosity = 0.1f, wets = false,
            coldAt = melt, coldTo = key, coldLatent = latent, inPalette = false, tags = tags, flame = flame,
            elec = if (elec.isNaN()) Float.NaN else elec * 0.3f)
    )

    private fun glow(c: Int): Int {
        val r = (c shr 16) and 0xFF
        val g = (c shr 8) and 0xFF
        return (minOf(255, r / 3 + 200) shl 16) or (minOf(255, g / 3 + 90) shl 8) or 0x30
    }

    /** Камень: плавится в лаву. */
    private fun rock(key: String, name: String, color: Int, density: Float, cp: Float, k: Float, melt: Float = 1200f,
                     to: String = "lava", latent: Float = 4e5f, tags: Int = 0, colorVar: Float = 0.1f, alpha: Float = 1f,
                     cat: C = C.STONE, bounce: Float = Float.NaN, grip: Float = Float.NaN, desc: String = "") =
        Substance(key, name, P.SOLID, cat, color, density = density, heatCapacity = cp, conductivity = k,
            colorVar = colorVar, alpha = alpha, hotAt = melt, hotTo = to, hotLatent = latent, tags = tags,
            bounce = bounce, grip = grip, description = desc)

    /** Порошок/соль. bulk — насыпная плотность, grain — плотность зерна. */
    private fun powder(key: String, name: String, color: Int, bulk: Float, grain: Float, cp: Float, k: Float = 0.3f,
                       friction: Float = 0.5f, tags: Int = 0, flame: Int = 0, cat: C = C.POWDER, colorVar: Float = 0.05f,
                       melt: Float = Float.NaN, to: String? = null, latent: Float = 0f, porosity: Float = 0f,
                       desc: String = "") =
        Substance(key, name, P.POWDER, cat, color, density = bulk, grainDensity = grain, heatCapacity = cp,
            conductivity = k, friction = friction, colorVar = colorVar, hotAt = melt, hotTo = to, hotLatent = latent,
            porosity = porosity, fieldCapacity = if (porosity > 0f) 0.5f else 0f, tags = tags, flame = flame,
            description = desc)

    /** Горючий порошок (пыль вспыхивает облаком). */
    private fun fuelPowder(key: String, name: String, color: Int, bulk: Float, grain: Float, cp: Float, heat: Float,
                           flash: Float, auto: Float, flameT: Float = 1200f, oxy: Float = 1.5f, fine: Float = 0.8f,
                           burnTime: Float = 2f, smoke: Float = 0.1f, burnTo: String? = "ash", residue: Float = 0.1f,
                           tags: Int = 0, flame: Int = 0, cat: C = C.POWDER, desc: String = "") =
        Substance(key, name, P.POWDER, cat, color, density = bulk, grainDensity = grain, heatCapacity = cp,
            conductivity = 0.15f, friction = 0.5f, colorVar = 0.08f, flashPoint = flash, autoIgnition = auto,
            burnTime = burnTime, burnHeat = heat, burnTo = burnTo, burnResidue = residue, smoke = smoke,
            flameTemp = flameT, oxygenNeed = oxy, fineness = fine, tags = tags or T.DUST, flame = flame,
            description = desc)

    /** Жидкость. */
    private fun liquid(key: String, name: String, color: Int, density: Float, cp: Float, k: Float = 0.5f,
                       boil: Float = 100f, vapor: String? = "steam", lv: Float = 2.26e6f, freeze: Float = 0f,
                       solid: String? = "ice", lf: Float = 3.3e5f, visc: Float = 0f, spread: Int = 5,
                       alpha: Float = 0.6f, vol: Float = 3e-6f, tags: Int = 0, flame: Int = 0, elec: Float = Float.NaN,
                       flash: Float = Float.NaN, auto: Float = Float.NaN, heat: Float = 0f, flameT: Float = 1200f,
                       smoke: Float = 0f, oxy: Float = 3f, burnTime: Float = 6f, spawnT: Float = Units.AMBIENT,
                       cure: Float = Float.NaN, curedTo: String? = null, cureAir: Boolean = true,
                       cat: C = C.LIQUID, wets: Boolean = true, desc: String = "") =
        Substance(key, name, P.LIQUID, cat, color, density = density, heatCapacity = cp, conductivity = k,
            expansion = 5e-4f, alpha = alpha, colorVar = 0.02f, spread = spread, viscosity = visc,
            volatility = vol, hotAt = if (vapor != null) boil else Float.NaN, hotTo = vapor, hotLatent = lv,
            coldAt = if (solid != null) freeze else Float.NaN, coldTo = solid, coldLatent = lf,
            flashPoint = flash, autoIgnition = auto, burnTime = burnTime, burnHeat = heat, smoke = smoke,
            flameTemp = flameT, oxygenNeed = oxy, spawnTemp = spawnT, cureTime = cure, curedTo = curedTo,
            cureNeedsAir = cureAir, wets = wets, tags = tags, flame = flame, elec = elec, description = desc)

    /** Газ. */
    private fun gas(key: String, name: String, color: Int, molar: Float, cp: Float, k: Float = 0.025f,
                    alpha: Float = 0.12f, condense: Float = Float.NaN, liquid: String? = null, lv: Float = 0f,
                    tags: Int = 0, flame: Int = 0, flash: Float = Float.NaN, auto: Float = Float.NaN, heat: Float = 0f,
                    flameT: Float = 1950f, oxy: Float = 3.5f, life: Float = Float.NaN, spawnT: Float = Units.AMBIENT,
                    desc: String = "") =
        Substance(key, name, P.GAS, C.GAS, color, molarMass = molar, heatCapacity = cp, conductivity = k,
            alpha = alpha, emissivity = 0.05f, coldAt = condense, coldTo = liquid, coldLatent = lv,
            flashPoint = flash, autoIgnition = auto, burnTime = 0.1f, burnHeat = heat, flameTemp = flameT,
            oxygenNeed = oxy, gasYield = if (heat > 0f) 2f else 0f, lifetime = life, spawnTemp = spawnT,
            tags = tags, flame = flame, description = desc)

    /** Горючее твёрдое (дерево, пластик, ткань…). */
    private fun burnable(key: String, name: String, color: Int, density: Float, cp: Float, k: Float, flash: Float,
                         auto: Float, burnTime: Float, heat: Float, burnTo: String? = "ash", residue: Float = 0.2f,
                         smoke: Float = 0.1f, flameT: Float = 1000f, oxy: Float = 1.4f, fine: Float = 0.3f,
                         charAt: Float = Float.NaN, charTo: String? = null, melt: Float = Float.NaN,
                         to: String? = null, latent: Float = 0f, cat: C = C.ORGANIC, tags: Int = T.ORGANIC,
                         flame: Int = 0, colorVar: Float = 0.06f, bounce: Float = Float.NaN, grip: Float = Float.NaN,
                         alpha: Float = 1f, elec: Float = Float.NaN, desc: String = "") =
        Substance(key, name, P.SOLID, cat, color, density = density, heatCapacity = cp, conductivity = k,
            colorVar = colorVar, alpha = alpha, elec = elec, flashPoint = flash, autoIgnition = auto, burnTime = burnTime,
            burnHeat = heat, burnTo = burnTo, burnResidue = residue, smoke = smoke, flameTemp = flameT,
            oxygenNeed = oxy, fineness = fine, charAt = charAt, charTo = charTo, hotAt = melt, hotTo = to,
            hotLatent = latent, tags = tags, flame = flame, bounce = bounce, grip = grip, description = desc)

    private fun wood(key: String, name: String, color: Int, density: Float, k: Float, burnTime: Float, desc: String,
                     fine: Float = 0.3f, resin: Boolean = false) =
        burnable(key, name, color, density, 1700f, k, if (resin) 260f else 300f, if (resin) 360f else 400f, burnTime,
            if (resin) 1.9e7f else 1.6e7f, residue = 0.25f, smoke = if (resin) 0.15f else 0.08f, fine = fine,
            charAt = 350f, charTo = "charcoal", colorVar = 0.08f, bounce = 0.3f, grip = 0.45f, desc = desc)

    /** Еда: вода + органика, при сильном нагреве обугливается. */
    private fun food(key: String, name: String, color: Int, density: Float, cp: Float = 3500f, k: Float = 0.5f,
                     desc: String = "", tags: Int = 0, colorVar: Float = 0.1f) =
        Substance(key, name, P.SOLID, C.FOOD, color, density = density, heatCapacity = cp, conductivity = k,
            colorVar = colorVar, charAt = 250f, charTo = "charcoal", tags = tags or T.FOOD or T.ORGANIC,
            bounce = 0.05f, description = desc)

    private fun foodPowder(key: String, name: String, color: Int, bulk: Float, grain: Float, fine: Float = 0.4f,
                           desc: String = "", tags: Int = 0) =
        Substance(key, name, P.POWDER, C.FOOD, color, density = bulk, grainDensity = grain, heatCapacity = 1800f,
            conductivity = 0.15f, friction = 0.55f, colorVar = 0.12f, flashPoint = 300f, autoIgnition = 400f,
            burnTime = 8f, burnHeat = 1.7e7f, burnTo = "ash", burnResidue = 0.15f, smoke = 0.15f, oxygenNeed = 1.3f,
            fineness = fine, charAt = 260f, charTo = "charcoal", tags = tags or T.FOOD or T.ORGANIC,
            description = desc)

    private fun foodLiquid(key: String, name: String, color: Int, density: Float, visc: Float = 0f,
                           tags: Int = 0, alpha: Float = 0.95f, desc: String = "") =
        liquid(key, name, color, density, 3600f, 0.5f, boil = 101f, vapor = "steam", freeze = -3f, solid = "ice",
            visc = visc, alpha = alpha, cat = C.FOOD, tags = tags or T.FOOD, desc = desc)

    /** Живое: растёт по правилам [Growth]. */
    private fun life(key: String, name: String, color: Int, density: Float = 700f, desc: String = "",
